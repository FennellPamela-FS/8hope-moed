// ─── Deterministic per-coordinate shuffle (idempotent under concurrent cold starts) ───

function hashSeed(s: string): number {
  let h = 1779033703 ^ s.length
  for (let i = 0; i < s.length; i++) {
    h = Math.imul(h ^ s.charCodeAt(i), 3432918353)
    h = (h << 13) | (h >>> 19)
  }
  return h >>> 0
}

function mulberry32(seed: number) {
  let s = seed
  return function () {
    s |= 0
    s = (s + 0x6d2b79f5) | 0
    let t = Math.imul(s ^ (s >>> 15), 1 | s)
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296
  }
}

function shuffle<T>(arr: T[], rng: () => number): T[] {
  const a = [...arr]
  for (let i = a.length - 1; i > 0; i--) {
    const j = Math.floor(rng() * (i + 1))
    ;[a[i], a[j]] = [a[j], a[i]]
  }
  return a
}

// Round-robins across categories so the candidate order tries diverse
// categories (Law, Wisdom, Gospels, Epistles, ...) before ever repeating one.
function diversityOrder(shuffled: string[]): string[] {
  const byCategory = new Map<string, string[]>()
  for (const code of shuffled) {
    const cat = CANON_BOOKS[code].category
    if (!byCategory.has(cat)) byCategory.set(cat, [])
    byCategory.get(cat)!.push(code)
  }
  const categories = [...byCategory.keys()]
  const result: string[] = []
  let i = 0
  while (result.length < shuffled.length) {
    for (const cat of categories) {
      const arr = byCategory.get(cat)!
      if (arr[i]) result.push(arr[i])
    }
    i++
  }
  return result
}

// ─── Live validation against the real Bible API (never trust a static count) ───

interface VerseFetchResult {
  text: string
  bookName: string
}

async function fetchVerseText(bibleId: string, book: string, chapter: number, verse: number, apiKey: string): Promise<VerseFetchResult | null> {
  const verseId = `${book}.${chapter}.${verse}`
  const res = await fetch(
    `${BIBLE_BASE}/bibles/${bibleId}/verses/${verseId}?content-type=text&include-notes=false&include-titles=false`,
    { headers: { 'api-key': apiKey } }
  )
  if (!res.ok) return null
  const data = await res.json()
  const clean = (data.data?.content ?? '')
    .replace(/<[^>]+>/g, '')
    .replace(/^\s*\[\d+\]\s*/, '')
    .trim()
  // The API's `reference` field is already localized per Bible ID (e.g. the
  // Spanish RVR09 returns "Génesis 1:1") — strip the trailing chapter:verse
  // to get just the book name, rather than hand-maintaining a translated
  // copy of CANON_BOOKS per language. Verified live for multi-word and
  // differently-named books ("1 Corintios", "Cantares" for Song of Solomon).
  const reference: string = data.data?.reference ?? ''
  const bookName = reference.replace(/\s+\d+:\d+.*$/, '').trim() || CANON_BOOKS[book]?.name || book
  return { text: clean, bookName }
}

interface SelectedRef {
  book: string
  chapter: number
  verse: number
  primaryText: string
  bookName: string
}

/**
 * Validates that a single (book, chapter, verse) genuinely exists across
 * every Bible version offered for `language`, returning the primary
 * version's text (for Gemini grounding) and localized book name if so.
 * Cross-checking multiple versions catches a translation-specific gap
 * (e.g. a disputed verse rendered blank in one edition) that a single
 * lookup would miss.
 */
async function validateCandidate(
  book: string, chapter: number, verse: number, language: Language, apiKey: string
): Promise<{ primaryText: string; bookName: string } | null> {
  const versions = VALIDATION_BIBLE_IDS_BY_LANGUAGE[language]
  const primaryCode = PRIMARY_VERSION_BY_LANGUAGE[language]

  const primary = await fetchVerseText(versions[primaryCode], book, chapter, verse, apiKey)
  if (!primary || primary.text.length < 10) return null

  for (const [code, id] of Object.entries(versions)) {
    if (code === primaryCode) continue
    const result = await fetchVerseText(id, book, chapter, verse, apiKey)
    if (!result || result.text.length < 10) return null
  }
  return { primaryText: primary.text, bookName: primary.bookName }
}

/**
 * Picks 3 distinct, category-diverse books that genuinely have chapter:verse
 * = month:day, cross-checked against every Bible version offered for
 * `language` so a translation-specific gap never slips through.
 */
async function selectVerses(month: number, day: number, language: Language, apiKey: string): Promise<SelectedRef[]> {
  const rng = mulberry32(hashSeed(`${month}:${day}`))
  const ordered = diversityOrder(shuffle(Object.keys(CANON_BOOKS), rng))

  const selected: SelectedRef[] = []
  for (const book of ordered) {
    if (selected.length === 3) break
    if (selected.some((s) => s.book === book)) continue

    const result = await validateCandidate(book, month, day, language, apiKey)
    if (!result) continue

    selected.push({ book, chapter: month, verse: day, primaryText: result.primaryText, bookName: result.bookName })
  }
  return selected
}

/**
 * If this (month, day) already has content in a different language, reuse
 * its exact 3 coordinates (after live-revalidating them against the new
 * language's Bible set) instead of independently re-selecting — keeps
 * "today's Moed" showing the same scriptures across languages, and is
 * strictly cheaper than a full walk (3 validations vs. however many
 * candidates the original walk rejected). Only applies to
 * moed_daily_content — month_numerology's per-language rows are
 * independent, hand-authored, and have no verse-existence concept.
 *
 * Returns null if no other-language row exists yet, or if any of its 3
 * coordinates fails to validate in the new language (rare versification
 * gap) — the caller falls back to a full independent selectVerses() call
 * in either case. Note this is a different failure trigger than the
 * concurrency race below: two simultaneous first-visitors in different
 * languages can both find no other-language row yet and both run a full
 * independent selection — usually converges anyway since selectVerses's
 * candidate order is fully deterministic per (month, day) regardless of
 * language, but can genuinely diverge in rare cases. Both are accepted
 * tradeoffs, same spirit as the existing same-language cold-start race.
 */
async function reuseCoordinatesFromOtherLanguage(
  month: number, day: number, language: Language, apiKey: string,
  supabase: ReturnType<typeof createClient>
): Promise<SelectedRef[] | null> {
  const other = await supabase
    .from('moed_daily_content')
    .select('verses')
    .eq('month', month)
    .eq('day', day)
    .neq('language', language)
    .limit(1)

  const otherRow = other.data?.[0] as { verses: Array<{ book_code: string; chapter: number; verse: number }> } | undefined
  if (!otherRow) return null

  const selected: SelectedRef[] = []
  for (const c of otherRow.verses) {
    const result = await validateCandidate(c.book_code, c.chapter, c.verse, language, apiKey)
    if (!result) return null
    selected.push({ book: c.book_code, chapter: c.chapter, verse: c.verse, primaryText: result.primaryText, bookName: result.bookName })
  }
  return selected
}

