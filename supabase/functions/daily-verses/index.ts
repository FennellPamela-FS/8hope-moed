/**
 * daily-verses Edge Function
 *
 * "The Moed Coordinate System": maps today's Gregorian date (month:day) to a
 * Chapter:Verse coordinate (e.g. Aug 13 -> 8:13), then selects THREE
 * distinct, real books of the Bible that validly have that chapter:verse,
 * and generates devotional content (Greek/Hebrew word insight + a
 * Tabernacle/Feast/agricultural-season "calendar connection") for each.
 *
 * Content is cached per (month, day, language) in `moed_daily_content` —
 * generated once per language, reused forever after (the coordinate for a
 * given calendar date is the same every year). Only this function (service
 * role) ever reads or writes moed_daily_content / month_numerology; both
 * tables have RLS enabled with zero policies on purpose (deny-all to
 * anon/authenticated).
 *
 * Multi-language: the SAME 3 book:chapter:verse coordinates are used across
 * languages for a given (month, day) — "today's Moed" is about which
 * scriptures are highlighted, not what language you read them in. When a
 * second language is requested for a date already generated in another
 * language, its coordinates are reused (after live-revalidating them
 * against the new language's Bible set) rather than re-selected from
 * scratch. See reuseCoordinatesFromOtherLanguage().
 *
 * Theological guardrail: Gemini is NEVER asked to name a book, chapter, or
 * verse — it only receives already-selected, already-verified references
 * and produces prose commentary in the requested language. Book identity
 * always comes from the fixed 66-book CANON_BOOKS map below (the
 * Protestant canon), and verse text is always fetched live from
 * scripture.api.bible, never generated by the AI.
 */

