/**
 * daily-verses Edge Function
 *
 * "The Moed Coordinate System": maps today's Gregorian date (month:day) to a
 * Chapter:Verse coordinate (e.g. Aug 13 -> 8:13), then selects THREE
 * distinct, real books of the Bible that validly have that chapter:verse,
 * and generates devotional content (Greek/Hebrew word insight + a
 * Tabernacle/Feast/agricultural-season "calendar connection") for each.
 *
 * Content is cached per (month, day) in `moed_daily_content` — generated
 * once, reused forever after (the coordinate for a given calendar date is
 * the same every year). Only this function (service role) ever reads or
 * writes moed_daily_content / month_numerology; both tables have RLS
 * enabled with zero policies on purpose (deny-all to anon/authenticated).
 *
 * Theological guardrail: Gemini is NEVER asked to name a book, chapter, or
 * verse — it only receives already-selected, already-verified references
 * and produces prose commentary. Book identity always comes from the fixed
 * 66-book CANON_BOOKS map below (the Protestant canon), and verse text is
 * always fetched live from scripture.api.bible, never generated by the AI.
 */

